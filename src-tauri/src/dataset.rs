use serde::Serialize;
use std::fs;
use std::path::{Path, PathBuf};

const IMAGE_EXTS: &[&str] = &["jpg", "jpeg", "png", "bmp", "webp", "tiff", "tif", "avif"];

#[derive(Debug, Serialize, Clone)]
pub struct DatasetInfo {
    pub yaml_path: String,
    pub train_count: usize,
    pub val_count: usize,
    pub class_names: Vec<String>,
}

/// source_dir 内のアノテーション付き画像を output_dir に YOLO データセット構造でコピーし
/// dataset.yaml を生成する。
///
/// 生成されるレイアウト:
/// ```
/// output_dir/
/// ├── images/
/// │   ├── train/
/// │   └── val/
/// ├── labels/
/// │   ├── train/
/// │   └── val/
/// └── dataset.yaml
/// ```
pub fn generate(
    source_dir: &str,
    output_dir: &str,
    val_ratio: f32,
) -> Result<DatasetInfo, String> {
    let source = Path::new(source_dir);
    let output = Path::new(output_dir);

    if !source.is_dir() {
        return Err(format!("ディレクトリが見つかりません: {}", source_dir));
    }
    if output == source {
        return Err("出力先にソースと同じディレクトリは指定できません".to_string());
    }
    let val_ratio = val_ratio.clamp(0.05, 0.5);

    // classes.txt 読み込み（必須）
    let classes_path = source.join("classes.txt");
    if !classes_path.exists() {
        return Err(
            "classes.txt が見つかりません。\
             先にアノテーションを「学習データとして保存」してください。"
                .to_string(),
        );
    }
    let class_names: Vec<String> = fs::read_to_string(&classes_path)
        .map_err(|e| format!("classes.txt 読み込みエラー: {}", e))?
        .lines()
        .map(|l| l.trim().to_string())
        .filter(|l| !l.is_empty())
        .collect();

    if class_names.is_empty() {
        return Err("classes.txt にクラス名が登録されていません".to_string());
    }

    // アノテーション付き画像を収集（ソースディレクトリの直下のみ）
    let pairs: Vec<(PathBuf, PathBuf)> = collect_annotated_pairs(source)?;

    if pairs.is_empty() {
        return Err(
            "アノテーション付きの画像が見つかりません。\
             画像に対してバウンディングボックスを作成し保存してください。"
                .to_string(),
        );
    }

    // シャッフル（LCG、seed 固定で再現性あり）
    let mut indices: Vec<usize> = (0..pairs.len()).collect();
    lcg_shuffle(&mut indices, 42);

    let val_count = ((pairs.len() as f32 * val_ratio).round() as usize).max(1);
    let train_count = pairs.len() - val_count;

    // ディレクトリ構造を作成
    for split in &["train", "val"] {
        fs::create_dir_all(output.join("images").join(split))
            .map_err(|e| format!("ディレクトリ作成エラー: {}", e))?;
        fs::create_dir_all(output.join("labels").join(split))
            .map_err(|e| format!("ディレクトリ作成エラー: {}", e))?;
    }

    // 画像・ラベルをコピー
    for (slot, &idx) in indices.iter().enumerate() {
        let split = if slot < train_count { "train" } else { "val" };
        copy_pair(&pairs[idx], output, split)?;
    }

    // dataset.yaml 生成
    let yaml_path = output.join("dataset.yaml");
    write_yaml(&yaml_path, output, &class_names)?;

    Ok(DatasetInfo {
        yaml_path: yaml_path.to_string_lossy().to_string(),
        train_count,
        val_count,
        class_names,
    })
}

// ── ヘルパー関数 ─────────────────────────────────────────────────

fn collect_annotated_pairs(source: &Path) -> Result<Vec<(PathBuf, PathBuf)>, String> {
    let mut pairs = Vec::new();

    let entries = fs::read_dir(source).map_err(|e| format!("ディレクトリ読み込みエラー: {}", e))?;

    for entry in entries {
        let entry = entry.map_err(|e| e.to_string())?;
        let img_path = entry.path();
        if !img_path.is_file() {
            continue;
        }

        let ext = img_path
            .extension()
            .and_then(|e| e.to_str())
            .unwrap_or("")
            .to_lowercase();

        if !IMAGE_EXTS.contains(&ext.as_str()) {
            continue;
        }

        let lbl_path = img_path.with_extension("txt");
        if !lbl_path.exists() {
            continue;
        }

        pairs.push((img_path, lbl_path));
    }

    Ok(pairs)
}

fn copy_pair(pair: &(PathBuf, PathBuf), output: &Path, split: &str) -> Result<(), String> {
    let (img_src, lbl_src) = pair;

    let img_dst = output
        .join("images")
        .join(split)
        .join(img_src.file_name().unwrap());
    let lbl_dst = output
        .join("labels")
        .join(split)
        .join(lbl_src.file_name().unwrap());

    fs::copy(img_src, &img_dst)
        .map_err(|e| format!("画像コピーエラー ({:?}): {}", img_src.file_name().unwrap(), e))?;
    fs::copy(lbl_src, &lbl_dst)
        .map_err(|e| format!("ラベルコピーエラー ({:?}): {}", lbl_src.file_name().unwrap(), e))?;

    Ok(())
}

fn write_yaml(yaml_path: &Path, output: &Path, class_names: &[String]) -> Result<(), String> {
    let names_block = class_names
        .iter()
        .map(|n| format!("  - {}", n))
        .collect::<Vec<_>>()
        .join("\n");

    let content = format!(
        "# Auto-generated by imGraph\npath: {}\ntrain: images/train\nval: images/val\n\nnc: {}\nnames:\n{}\n",
        output.display(),
        class_names.len(),
        names_block,
    );

    fs::write(yaml_path, content)
        .map_err(|e| format!("dataset.yaml 書き込みエラー: {}", e))
}

// LCG ベースの Fisher-Yates シャッフル（外部クレート不要）
fn lcg_shuffle(indices: &mut Vec<usize>, seed: u64) {
    let mut rng = seed;
    for i in (1..indices.len()).rev() {
        rng = rng
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        let j = (rng >> 33) as usize % (i + 1);
        indices.swap(i, j);
    }
}
